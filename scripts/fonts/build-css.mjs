#!/usr/bin/env node
/**
 * public/fonts/manifest.json -> public/fonts/sheet-fonts.css, and its content hash into
 * src/constants/sheetFontsVersion.ts.
 *
 * One `@font-face` per weight/style a font ships. The family name is `sf-<slug>` — the same
 * string `sheetFontFamily()` in src/constants/fonts.ts produces — so a list's design stores a slug
 * and never a raw font-family string. Browsers download a face only when text uses it, so
 * declaring all twenty costs nothing until the editor's font picker or a sheet asks for one.
 *
 * `/fonts/` is cached for a year, `immutable` (next.config.ts, the nginx site), so nothing is
 * fetched under the same URL twice: each face's URL carries a hash of its file, and the
 * stylesheet's (`SHEET_FONTS_STYLESHEET`) a hash of the stylesheet — a changed face changes both.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const fontsDir = path.join(root, 'public/fonts')
const hashOf = (data) => createHash('sha256').update(data).digest('hex').slice(0, 10)
const manifest = JSON.parse(readFileSync(path.join(fontsDir, 'manifest.json'), 'utf8'))

const faces = Object.entries(manifest).flatMap(([slug, entries]) =>
  entries.map(
    (face) =>
      `@font-face {\n  font-family: 'sf-${slug}';\n  src: url('/fonts/${face.file}?v=${hashOf(readFileSync(path.join(fontsDir, face.file)))}') format('woff2');\n` +
      `  font-weight: ${face.weight};\n  font-style: ${face.style};\n  font-display: swap;\n}\n`
  )
)

const css = `/* Generated by scripts/fonts/build-css.mjs from manifest.json — do not edit. */\n\n${faces.join('\n')}`
writeFileSync(path.join(fontsDir, 'sheet-fonts.css'), css)
writeFileSync(
  path.join(root, 'src/constants/sheetFontsVersion.ts'),
  `/** Generated by scripts/fonts/build-css.mjs — do not edit. A hash of public/fonts/sheet-fonts.css. */\n` +
    `export const SHEET_FONTS_VERSION = '${hashOf(css)}'\n`
)
console.log(`[fonts] ${faces.length} faces -> public/fonts/sheet-fonts.css`)
